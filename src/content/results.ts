function elo(
  rank: number,
  spread: string,
  modelSlug: string,
  effort: string | undefined,
  score: number,
  ci: number,
  votes: string,
  tokenPrice: string,
  context?: string,
  preliminary?: boolean,
): Result {
  return {
    benchmark: web,
    asOf: webDate,
    rank,
    rankSpread: spread,
    modelSlug,
    effort: effort || undefined,
    setting: effort || undefined,
    score,
    ci: { kind: "pm", value: ci },
    votes,
    tokenPrice,
    context,
    preliminary,
  };
}

function fw(
  benchmark: string,
  asOf: string,
  modelSlug: string,
  score: number,
  extra: Partial<Result> = {},
): Result {
  return { benchmark, asOf, modelSlug, score, arm: extra.arm ?? "baseline", ...extra };
}

