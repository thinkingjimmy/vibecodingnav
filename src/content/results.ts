import type { Result } from "@/lib/contracts";

const web = "lmarena-webdev";
const webDate = "2026-10-08";

function elo(
  rank: number,
  spread: string,
  modelSlug: string,
  effort: string | undefined,
  score: number,
  ci: number,
  votes: string,
  tokenPrice: string,
  context?: string,
  preliminary?: boolean,
): Result {
  return {
    benchmark: web,
    asOf: webDate,
    rank,
    rankSpread: spread,
    modelSlug,
    effort: effort || undefined,
    setting: effort || undefined,
    score,
    ci: { kind: "pm", value: ci },
    votes,
    tokenPrice,
    context,
    preliminary,
  };
}

